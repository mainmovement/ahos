# AHOS Portable Bundle Setup Script
# This script installs AHOS to a permanent location on the system

param(
    [string]$TargetDir,
    [switch]$Silent = $false,
    [switch]$Force = $false,
    [switch]$Help = $false
)

# Color functions for output
function Write-HostColor {
    param(
        [string]$Message,
        [string]$Color = "White"
    )
    if (-not $Silent) {
        Write-Host $Message -ForegroundColor $Color
    }
}

# Check if running with administrator privileges
function Test-Admin {
    $currentUser = New-Object Security.Principal.WindowsPrincipal([Security.Principal.WindowsIdentity]::GetCurrent())
    return $currentUser.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)
}

# Get default installation path
function Get-DefaultInstallPath {
    $programFiles = [Environment]::GetFolderPath("ProgramFiles")
    return Join-Path $programFiles "AHOS_Portable"
}

# Copy files to installation directory
function Copy-AHOSFiles {
    param(
        [string]$SourceDir,
        [string]$DestDir
    )

    Write-HostColor "`n=== Copying AHOS files ===" "Green"

    # Create destination directory
    if (-not (Test-Path $DestDir)) {
        New-Item -ItemType Directory -Path $DestDir -Force | Out-Null
        Write-HostColor "Created directory: $DestDir" "Green"
    }

    # Copy all files
    Copy-Item -Path "$SourceDir\*" -Destination $DestDir -Recurse -Force

    # Verify files were copied
    $expectedFiles = @(
        "ahos_launcher.exe",
        "ahos_launcher.ps1",
        "HEALTH_CHECK.ps1",
        "M62_PORTABLE_README.md",
        "M62_INSTALL_GUIDE.md",
        "CREATE_DESKTOP_SHORTCUT.ps1"
    )

    foreach ($file in $expectedFiles) {
        $filePath = Join-Path $DestDir $file
        if (Test-Path $filePath) {
            Write-HostColor "✓ Copied: $file" "Green"
        } else {
            Write-HostColor "✗ Missing: $file" "Red"
            throw "File copy failed: $file"
        }
    }

    Write-HostColor "✓ All files copied successfully" "Green"
}

# Configure AHOS for the system
function Configure-AHOS {
    param(
        [string]$InstallDir
    )

    Write-HostColor "`n=== Configuring AHOS ===" "Green"

    # Set environment variables
    $envPath = [Environment]::GetFolderPath("UserProfile") + "\ahos-env.ps1"

    @"
# AHOS Environment Variables
# This file is automatically generated by the AHOS installer

# AHOS Installation Path
`$AHOS_INSTALL_PATH = "$InstallDir"

# Python path
`$env:PYTHONPATH = "`$AHOS_INSTALL_PATH\env;`$env:PYTHONPATH"

# Add AHOS to PATH
`$env:PATH = "`$AHOS_INSTALL_PATH\env;`$env:PATH"

# AHOS data path
`$env:AHOS_DATA_PATH = "`$AHOS_INSTALL_PATH\data"

# AHOS logs path
`$env:AHOS_LOGS_PATH = "`$AHOS_INSTALL_PATH\data\logs"

# Initialize data directory
if (-not (Test-Path "`$AHOS_DATA_PATH")) {
    New-Item -ItemType Directory -Path "`$AHOS_DATA_PATH" -Force | Out-Null
}
if (-not (Test-Path "`$AHOS_LOGS_PATH")) {
    New-Item -ItemType Directory -Path "`$AHOS_LOGS_PATH" -Force | Out-Null
}
"@ | Out-File -FilePath $envPath -Encoding UTF8

    Write-HostColor "✓ Environment configuration saved: $envPath" "Green"

    # Create desktop shortcut
    $shortcutScript = Join-Path $InstallDir "CREATE_DESKTOP_SHORTCUT.ps1"
    & $shortcutScript

    # Create Start Menu shortcut
    $startMenuPath = [Environment]::GetFolderPath("Programs") + "\AHOS Portable.lnk"
    $shell = New-Object -ComObject WScript.Shell
    $shortcut = $shell.CreateShortcut($startMenuPath)
    $shortcut.TargetPath = Join-Path $InstallDir "ahos_launcher.ps1"
    $shortcut.WorkingDirectory = $InstallDir
    $shortcut.Description = "AHOS Portable - Automated Hybrid Operating System"
    $shortcut.Save()

    Write-HostColor "✓ Start Menu shortcut created" "Green"
}

# Register uninstaller
function Register-Uninstaller {
    param(
        [string]$InstallDir
    )

    Write-HostColor "`n=== Registering uninstaller ===" "Green"

    $uninstallerPath = Join-Path $InstallDir "UNINSTALL.ps1"
    $uninstallerContent = @"
# AHOS Portable Uninstaller

param(
    [string]$InstallDir,
    [switch]$Confirm = `$false
)

if (-not `$Confirm) {
    Write-Host "This will uninstall AHOS Portable from '$InstallDir'" -ForegroundColor Yellow
    Write-Host "Are you sure? Press Y to continue, any other key to cancel."

    `$response = Read-Host
    if (`$response -ne "Y" -and `$response -ne "y") {
        Write-Host "Uninstallation cancelled." -ForegroundColor Green
        exit 0
    }
}

Write-Host "Uninstalling AHOS Portable..." -ForegroundColor Yellow

# Remove desktop shortcut
`$desktopPath = [Environment]::GetFolderPath("Desktop")
`$desktopShortcut = Join-Path `$desktopPath "AHOS Portable.lnk"
if (Test-Path `$desktopShortcut) {
    Remove-Item `$desktopShortcut -Force
    Write-Host "✓ Removed desktop shortcut" -ForegroundColor Green
}

# Remove Start Menu shortcut
`$startMenuPath = [Environment]::GetFolderPath("Programs") + "\AHOS Portable.lnk"
if (Test-Path `$startMenuPath) {
    Remove-Item `$startMenuPath -Force
    Write-Host "✓ Removed Start Menu shortcut" -ForegroundColor Green
}

# Remove AHOS directory
if (Test-Path `$InstallDir) {
    Remove-Item `$InstallDir -Recurse -Force
    Write-Host "✓ Removed AHOS installation" -ForegroundColor Green
}

# Remove environment configuration
`$envPath = [Environment]::GetFolderPath("UserProfile") + "\ahos-env.ps1"
if (Test-Path `$envPath) {
    Remove-Item `$envPath -Force
    Write-Host "✓ Removed environment configuration" -ForegroundColor Green
}

Write-Host "AHOS Portable has been successfully uninstalled." -ForegroundColor Green
"@

    $uninstallerContent | Out-File -FilePath $uninstallerPath -Encoding UTF8

    # Register in Add/Remove Programs
    $uninstallRegPath = "HKCU:\Software\Microsoft\Windows\CurrentVersion\Uninstall\AHOS_Portable"
    New-Item -Path $uninstallRegPath -Force | Out-Null
    New-ItemProperty -Path $uninstallRegPath -Name "DisplayName" -Value "AHOS Portable" -PropertyType String -Force | Out-Null
    New-ItemProperty -Path $uninstallRegPath -Name "DisplayVersion" -Value "1.0" -PropertyType String -Force | Out-Null
    New-ItemProperty -Path $uninstallRegPath -Name "Publisher" -Value "AHOS Project" -PropertyType String -Force | Out-Null
    New-ItemProperty -Path $uninstallRegPath -Name "InstallLocation" -Value $InstallDir -PropertyType String -Force | Out-Null
    New-ItemProperty -Path $uninstallRegPath -Name "UninstallString" -Value "powershell.exe -ExecutionPolicy Bypass -File `"$uninstallerPath`"" -PropertyType String -Force | Out-Null
    New-ItemProperty -Path $uninstallRegPath -Name "ModifyPath" -Value "powershell.exe -ExecutionPolicy Bypass -File `"$uninstallerPath`"" -PropertyType String -Force | Out-Null
    New-ItemProperty -Path $uninstallRegPath -Name "QuietUninstallString" -Value "powershell.exe -ExecutionPolicy Bypass -File `"$uninstallerPath`"" -PropertyType String -Force | Out-Null
    New-ItemProperty -Path $uninstallRegPath -Name "NoModify" -Value 1 -PropertyType DWord -Force | Out-Null
    New-ItemProperty -Path $uninstallRegPath -Name "NoRepair" -Value 1 -PropertyType DWord -Force | Out-Null
    New-ItemProperty -Path $uninstallRegPath -Name "DisplayIcon" -Value "`"$InstallDir\ahos_icon.ico`"" -PropertyType String -Force | Out-Null

    Write-HostColor "✓ Uninstaller registered" "Green"
}

# Run health check
function Test-Installation {
    param(
        [string]$InstallDir
    )

    Write-HostColor "`n=== Testing installation ===" "Green"

    Push-Location $InstallDir
    try {
        & "HEALTH_CHECK.ps1"
        $healthExitCode = $LASTEXITCODE
    }
    finally {
        Pop-Location
    }

    if ($healthExitCode -eq 0) {
        Write-HostColor "✓ Installation test passed" "Green"
    } else {
        Write-HostColor "⚠ Installation test failed with code $healthExitCode" "Yellow"
        if (-not $Force) {
            Write-HostColor "Consider running HEALTH_CHECK.ps1 manually to diagnose issues" "Yellow"
        }
    }
}

# Show help
if ($Help) {
    Write-HostColor "AHOS Portable Bundle Installer" "Green"
    Write-HostColor ""
    Write-HostColor "Usage: .\INSTALL.ps1 [OPTIONS]" "White"
    Write-HostColor ""
    Write-HostColor "Options:" "White"
    Write-HostColor "  -TargetDir <path>     Installation directory (default: C:\Program Files\AHOS_Portable)" "Cyan"
    Write-HostColor "  -Silent              Run without confirmation prompts" "Cyan"
    Write-HostColor "  -Force               Force installation even if tests fail" "Cyan"
    Write-HostColor "  -Help               Show this help message" "Cyan"
    Write-HostColor ""
    Write-HostColor "Requirements:" "White"
    Write-HostColor "  - Windows 10 or later" "Yellow"
    Write-HostColor "  - Administrator privileges" "Yellow"
    Write-HostColor "  - Internet connection for first-time setup" "Yellow"
    exit 0
}

# Check admin privileges
if (-not (Test-Admin)) {
    Write-HostColor "Error: Administrator privileges are required to install AHOS Portable" "Red"
    Write-HostColor "Please run this script as an administrator." "Red"
    exit 1
}

# Get target directory
if (-not $TargetDir) {
    $TargetDir = Get-DefaultInstallPath
}

# Show installation summary
Write-HostColor "AHOS Portable Bundle Installer" "Green"
Write-HostColor "==============================" "Green"
Write-HostColor "Install Location: $TargetDir" "White"
Write-HostColor "Source Location: $(Get-Location)" "White"
Write-HostColor "Administrator: Yes" "White"

# Silent mode confirmation
if (-not $Silent) {
    Write-HostColor ""
    Write-HostColor "Ready to install AHOS Portable? Press Y to continue, any other key to cancel." "Yellow"

    $response = Read-Host
    if ($response -ne "Y" -and $response -ne "y") {
        Write-HostColor "Installation cancelled." "Green"
        exit 0
    }
}

# Perform installation
try {
    Copy-AHOSFiles -SourceDir (Get-Location).Path -DestDir $TargetDir
    Configure-AHOS -InstallDir $TargetDir
    Register-Uninstaller -InstallDir $TargetDir
    Test-Installation -InstallDir $TargetDir

    Write-HostColor ""
    Write-HostColor "==============================" "Green"
    Write-HostColor "Installation Complete!" "Green"
    Write-HostColor "==============================" "Green"
    Write-HostColor ""
    Write-HostColor "To start AHOS:" "White"
    Write-HostColor "1. Open Windows Credential Manager and add your API keys" "Cyan"
    Write-HostColor "2. Run $TargetDir\ahos_launcher.ps1" "Cyan"
    Write-HostColor "3. Or use the desktop shortcut" "Cyan"
    Write-HostColor ""
    Write-HostColor "To run health check:" "White"
    Write-HostColor "$TargetDir\HEALTH_CHECK.ps1" "Cyan"
    Write-HostColor ""
    Write-HostColor "To uninstall:" "White"
    Write-HostColor "$TargetDir\UNINSTALL.ps1" "Cyan"

    exit 0
}
catch {
    Write-HostColor ""
    Write-HostColor "==============================" "Red"
    Write-HostColor "Installation Failed!" "Red"
    Write-HostColor "Error: $_" "Red"
    Write-HostColor "==============================" "Red"
    exit 1
}